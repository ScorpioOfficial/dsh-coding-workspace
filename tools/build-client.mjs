/**
 * Build the shipped client module from two parts:
 *
 *   node tools/build-client.mjs
 *
 * 1. `tools/xterm-entry.js` is bundled into an IIFE that parks xterm on
 *    `window.__PythonWorkspaceXterm`.
 * 2. `src/client.js` — the plain-JavaScript plugin source — is appended after it.
 *
 * The result is one `client.js` the module loader can execute directly: xterm is
 * available before the factory runs, and the source stays readable (never edit
 * the generated `client.js`; edit `src/client.js` and rebuild).
 */
import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const vendor = `${root}/.build/xterm.js`

await mkdir(`${root}/.build`, { recursive: true })
await build({
  entryPoints: [`${root}/tools/xterm-entry.js`],
  outfile: vendor,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome110', 'firefox115', 'safari16'],
  loader: { '.css': 'text' },
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
})

const [bundle, source] = await Promise.all([
  readFile(vendor, 'utf8'),
  readFile(`${root}/src/client.js`, 'utf8'),
])

await writeFile(`${root}/client.js`, `/* generated by tools/build-client.mjs — edit src/client.js instead */\n${bundle}\n${source}`)
const total = Buffer.byteLength(bundle) + Buffer.byteLength(source)
console.log(`client.js written (${Math.round(total / 1024)} kb)`)
